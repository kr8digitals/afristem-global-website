/**
 * Uploaded images live in the Supabase Storage bucket "media" (public read).
 * The website keeps serving them at /api/media/<file> (see
 * src/app/api/media/[...path]/route.ts), so content never depends on the
 * storage provider's URL.
 *
 * Payment receipts live in the PRIVATE bucket "receipts": nobody can read them
 * with the public key. Only the website server (service_role) can upload, and
 * admins open a file through a short-lived signed URL created here.
 */
import "server-only";
import { db, storageBaseUrl } from "@/lib/db";

export const MEDIA_BUCKET = "media";
export const RECEIPTS_BUCKET = "receipts";

/** Upload file names the site generates: <time>-<random>.jpg */
export const SAFE_MEDIA_NAME = /^[a-z0-9][a-z0-9._-]{0,200}\.(jpe?g|png|webp|avif|gif)$/i;

export async function uploadToStorage(name: string, body: Buffer, contentType: string): Promise<void> {
  const { error } = await db()
    .storage.from(MEDIA_BUCKET)
    .upload(name, body, { contentType, upsert: false, cacheControl: "31536000" });
  if (error) throw new Error(`Storage upload failed: ${error.message}`);
}

/** Public URL of a stored file (the bucket is public). */
export function storagePublicUrl(name: string): string {
  return `${storageBaseUrl()}/object/public/${MEDIA_BUCKET}/${encodeURIComponent(name)}`;
}

/* ---------------------------------------------------------------- receipts */

/**
 * Receipt object paths look like "AFR-2026-1F4C9/1729600000000-a1b2c3.pdf".
 * They are generated by the server, never taken from the browser.
 */
export const SAFE_RECEIPT_PATH = /^[A-Z0-9-]{4,40}\/[a-z0-9][a-z0-9._-]{0,120}\.(jpe?g|png|webp|pdf)$/i;

/** Stores a receipt in the private bucket. Never returns a public URL. */
export async function uploadReceipt(path: string, body: Buffer, contentType: string): Promise<void> {
  const { error } = await db().storage.from(RECEIPTS_BUCKET).upload(path, body, {
    contentType,
    upsert: false,
    cacheControl: "no-store",
  });
  if (error) throw new Error(`Storage upload failed: ${error.message}`);
}

/** A link that works for a couple of minutes — used by the admin review screen. */
export async function receiptSignedUrl(path: string, seconds = 120): Promise<string | null> {
  const { data, error } = await db().storage.from(RECEIPTS_BUCKET).createSignedUrl(path, seconds);
  if (error || !data?.signedUrl) return null;
  return data.signedUrl;
}

/** Removes a receipt that was uploaded but could not be recorded. */
export async function deleteReceipt(path: string): Promise<void> {
  await db().storage.from(RECEIPTS_BUCKET).remove([path]);
}
